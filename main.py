from inventory import select, add, search

while True:
    print("\nПривет! Это приложение нашей команды!")
    print("Это приложение для учёта компьютерного оборудования.")
    print("Приложение, позволяет просматривать, добавлять, изменять, удалять и искать инвентарные записи как оборудования, так и позволяет искать само оборудование.\n")
    print("Чтобы им воспользоваться вам необходимо выбрать действие и написать цифру этого действия:")
    print("1.Посмотереть всё оборудование \n2.Посмотреть один объект \n3.Добавить объект \n4.Удалить объект \n0.Выход\n")
    try:
        choice = int(input("Выберете цифру: "))
    except ValueError :
        print("Вам нужно написать цифру из списка \n")
        continue

    if choice == 1:
        select()
    elif choice == 2:
        id = input("Инвентарный номер: ")
        search(id)
    elif choice == 3:
        add()
    elif choice == 4:
        print("Тут функция 'Удалить'\n")
    elif choice == 0:
        print("До свидания, гость")
        break
    else:
        print("Вы ввели кажется не ту цифру, введите цифу из списка")

